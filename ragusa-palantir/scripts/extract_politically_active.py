def build_rows():
    """Build full row list with footnotes attached."""
    rows = []
    for row_data in ROWS:
        (id_, surname, name, father, grandfather, hackenberg,
         entry_year, entry_source, end_year, end_type, fn_nums) = row_data
        notes = " | ".join(FOOTNOTES[n] for n in fn_nums) if fn_nums else ""
        rows.append({
            "id": id_,
            "surname": surname,
            "name": name,
            "father": father,
            "grandfather": grandfather,
            "hackenberg_number": hackenberg,
            "entry_year": entry_year,
            "entry_source": entry_source,
            "end_year": end_year,
            "end_type": end_type,
            "notes": notes,
        })
    return rows


def validate(rows):
    """Run validation checks on extracted data."""
    ids = [r["id"] for r in rows]
    print(f"Total rows: {len(rows)}")
    print(f"Unique IDs: {len(set(ids))}")

    # Check for duplicate IDs
    from collections import Counter
    dupes = [id_ for id_, count in Counter(ids).items() if count > 1]
    if dupes:
        print(f"WARNING: Duplicate IDs: {dupes}")

    # Check surnames
    empty_surnames = [r for r in rows if not r["surname"]]
    if empty_surnames:
        print(f"WARNING: {len(empty_surnames)} rows with empty surname")

    # Check entry_source values
    valid_sources = {"", "1stOff", "Ballot", "1stNom", "EntYr", "EntRel"}
    bad_sources = [r for r in rows if r["entry_source"] not in valid_sources]
    if bad_sources:
        print(f"WARNING: Invalid entry_source values: {set(r['entry_source'] for r in bad_sources)}")

    # Check end_type values
    valid_types = {"", "Period", "LastOff", "LastNom", "EntRel", "LastOff", "LastNom"}
    bad_types = [r for r in rows if r["end_type"] not in valid_types]
    if bad_types:
        print(f"WARNING: Invalid end_type values: {set(r['end_type'] for r in bad_types)}")

    # Spot checks
    spot_checks = {
        18: ("Babalio", "Andreas", "1421", "1473"),
        582: ("Zrieva", "Cugno", "1432", "1485"),
    }
    for id_, expected in spot_checks.items():
        row = next((r for r in rows if r["id"] == id_), None)
        if row:
            actual = (row["surname"], row["name"], row["entry_year"], row["end_year"])
            if actual == expected:
                print(f"  Spot check ID {id_}: PASS")
            else:
                print(f"  Spot check ID {id_}: FAIL (expected {expected}, got {actual})")
        else:
            print(f"  Spot check ID {id_}: NOT FOUND")

    # Surname distribution
    surnames = sorted(set(r["surname"] for r in rows))
    print(f"Distinct surnames: {len(surnames)}")
    print(f"  {', '.join(surnames)}")

    # PDF text says "813 men" but table actually contains 814 distinct entries
    return len(rows) == 814


def write_csv(rows, output_path):
    """Write rows to CSV file."""
    fieldnames = [
        "id", "surname", "name", "father", "grandfather",
        "hackenberg_number", "entry_year", "entry_source",
        "end_year", "end_type", "notes",
    ]
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    with open(output_path, "w", newline="", encoding="utf-8-sig") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)
    print(f"Wrote {len(rows)} rows to {output_path}")


def main():
    import argparse
    parser = argparse.ArgumentParser(
        description="Generate CSV of politically active men from PDF appendix data"
    )
    parser.add_argument(
        "--output",
        default=os.path.join(os.path.dirname(__file__), "..", "data", "politically_active_men.csv"),
        help="Output CSV path",
    )
    parser.add_argument("--validate-only", action="store_true", help="Only validate, don't write")
    args = parser.parse_args()

    rows = build_rows()

    if args.validate_only:
        validate(rows)
    else:
        write_csv(rows, args.output)
        validate(rows)


if __name__ == "__main__":
    main()
